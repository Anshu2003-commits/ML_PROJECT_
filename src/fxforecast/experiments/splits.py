"""Describe the evaluation splits on the real data (milestone M3).

    python -m fxforecast.experiments.splits

Writes results/splits/README.md (fold table per scheme and horizon) and a
fold diagram, so the report's methodology section shows exactly what was
trained and tested.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from fxforecast.config import DEFAULT_CONFIG, PROJECT_ROOT, load_config, resolve_path
from fxforecast.evaluation.splits import replication_folds, walk_forward_folds
from fxforecast.features.supervised import make_supervised
from fxforecast.features.transforms import macro_differentials
from fxforecast.reporting import plots
from fxforecast.reporting.tables import to_markdown


def fold_table(folds, horizon: int) -> pd.DataFrame:
    rows = [{
        "refit": f"{f.refit_date:%Y-%m}",
        "train origins": f"{f.train[0]:%Y-%m} to {f.train[-1]:%Y-%m}",
        "n_train": len(f.train),
        "test origins": f"{f.test[0]:%Y-%m} to {f.test[-1]:%Y-%m}",
        "test targets": f"{f.test[0] + pd.DateOffset(months=horizon):%Y-%m} to "
                        f"{f.test[-1] + pd.DateOffset(months=horizon):%Y-%m}",
        "n_test": len(f.test),
    } for f in folds]
    return pd.DataFrame(rows).set_index("refit")


def run(cfg: dict, out_dir: Path) -> Path:
    n_lags = cfg["features"]["max_lags"]
    panel = pd.read_parquet(resolve_path(cfg["data"]["processed_dir"]) / "panel.parquet")
    feats = macro_differentials(panel)
    rep, wf = cfg["experiments"]["replication"], cfg["experiments"]["walk_forward"]
    sections = []
    for h in wf["horizons"]:
        # use the largest feature set so every model shares the same origins
        X, _ = make_supervised(feats, "fx_plus_macro", n_lags=n_lags, horizon=h)
        wf_folds = walk_forward_folds(X.index, pd.Timestamp(wf["first_origin"]), wf["refit_every_months"], h)
        if h == 1:
            plots.fold_diagram(wf_folds, out_dir / "walk_forward_h1.png",
                               title="Expanding-window walk-forward, h = 1")
        sections.append(f"### Walk-forward, h = {h} ({sum(len(f.test) for f in wf_folds)} test forecasts)\n\n"
                        + to_markdown(fold_table(wf_folds, h)))
        if h in rep["horizons"]:
            rep_folds = replication_folds(X.index, pd.Timestamp(rep["train_end"]), pd.Timestamp(rep["test_end"]), h)
            sections.insert(0, f"### Replication of the paper, h = {h}\n\n" + to_markdown(fold_table(rep_folds, h)))

    md = f"""# Evaluation splits (M3)

Generated by `python -m fxforecast.experiments.splits`. Rows are **forecast origins** t: the model sees data up to t and predicts log FX(t+h) - log FX(t).
At a refit date T the model trains only on origins with t + h <= T (targets already observed), then forecasts every origin until the next refit. Feature rows use {n_lags} lags, so the first usable origin is {X.index[0]:%Y-%m}.

![walk-forward folds](walk_forward_h1.png)

{chr(10).join(s + chr(10) for s in sections)}"""
    out_dir.mkdir(parents=True, exist_ok=True)
    report = out_dir / "README.md"
    report.write_text(md, encoding="utf-8")
    return report


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", default=str(DEFAULT_CONFIG))
    parser.add_argument("--out", default=str(PROJECT_ROOT / "results" / "splits"))
    args = parser.parse_args(argv)
    print(run(load_config(args.config), Path(args.out)))


if __name__ == "__main__":
    main()
