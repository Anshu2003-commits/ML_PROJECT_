"""Exploratory analysis and statistical diagnostics (milestone M2).

    python -m fxforecast.experiments.eda

Reads data/processed/panel.parquet and writes results/eda/:
    README.md   report with all tables and figure links
    figures/    PNG charts
    tables/     CSV versions of every table

Diagnostics that drive modelling choices (differencing, lag order, VAR vs VECM)
are computed on the paper's training period only (up to replication.train_end),
so the test period never influences the model specification.
"""
from __future__ import annotations

import argparse
import logging
import time
from pathlib import Path

import numpy as np
import pandas as pd

from fxforecast.config import DEFAULT_CONFIG, PROJECT_ROOT, load_config, resolve_path
from fxforecast.features import diagnostics as dg
from fxforecast.features.transforms import TARGET, difference, macro_differentials, relative_levels
from fxforecast.reporting import plots
from fxforecast.reporting.tables import to_markdown

log = logging.getLogger("fxforecast.eda")


def log_levels(panel: pd.DataFrame) -> pd.DataFrame:
    """Log of every strictly positive raw series; rates stay in levels."""
    out = {}
    for c in panel.columns:
        if c.startswith("rate") or (panel[c] <= 0).any():
            out[c] = panel[c]
        else:
            out[f"log_{c}"] = np.log(panel[c])
    return pd.DataFrame(out, index=panel.index)


def run(cfg: dict, out_dir: Path) -> Path:
    started = time.perf_counter()
    panel_path = resolve_path(cfg["data"]["processed_dir"]) / "panel.parquet"
    if not panel_path.exists():
        raise FileNotFoundError(f"{panel_path} missing; run `python -m fxforecast.data` first")
    panel = pd.read_parquet(panel_path)
    rep = {k: (pd.Timestamp(v) if k.startswith(("train", "test")) else v)
           for k, v in cfg["experiments"]["replication"].items()}
    train_end = rep["train_end"]
    test_window = (rep["test_start"], rep["test_end"], "paper test period")

    feats = macro_differentials(panel)
    feats_train = feats.loc[:train_end]
    levels_train = relative_levels(panel).loc[:train_end]
    fig_dir, tab_dir = out_dir / "figures", out_dir / "tables"
    tab_dir.mkdir(parents=True, exist_ok=True)

    # --- Figures -----------------------------------------------------------
    plots.small_multiples(panel, fig_dir / "raw_series.png", title="Raw FRED series, 1994-2023")
    plots.small_multiples(feats, fig_dir / "features.png", title="Target and US-India differentials",
                          zero_line=True, shade=test_window)
    plots.correlation_heatmap(feats_train, fig_dir / "correlation_train.png",
                              title=f"Correlation of features (train, to {train_end:%Y-%m})")
    plots.acf_plot(feats_train[TARGET], fig_dir / "acf_dlog_fx.png",
                   title="ACF of monthly USD/INR log change (train)")

    # --- Stationarity --------------------------------------------------------
    stat_levels = dg.stationarity_table(log_levels(panel).loc[:train_end])
    stat_feats = dg.stationarity_table(feats_train)
    orders = {c: dg.integration_order(feats_train[c]) for c in feats_train.columns}
    stat_feats["diff_order_used"] = pd.Series(orders)
    feats_stationary = difference(feats_train, orders)

    # --- Granger, lag order, cointegration, autocorrelation -------------------
    granger = dg.granger_table(feats_stationary, TARGET)
    lag_sel = dg.var_lag_selection(feats_stationary, max_lags=cfg["models"]["var"]["max_lag"])
    lev_lag = dg.var_lag_selection(levels_train, max_lags=cfg["models"]["var"]["max_lag"])["aic"]
    johansen, rank = dg.johansen_table(levels_train, k_ar_diff=max(lev_lag - 1, 1))
    lb = dg.ljung_box(feats_train[TARGET])
    corr_target = feats_train.corr()[TARGET].drop(TARGET).sort_values(key=abs, ascending=False)

    # naive random-walk reference on the paper's test window (level MAPE)
    fx = panel["fx"]
    test = fx.loc[rep["test_start"]:rep["test_end"]]
    rw_pred = fx.shift(1).loc[test.index]
    rw_mape = float((abs(rw_pred - test) / test).mean())

    tables = {
        "stationarity_levels": stat_levels, "stationarity_features": stat_feats,
        "granger": granger, "johansen": johansen, "ljung_box": lb,
    }
    for name, df in tables.items():
        df.to_csv(tab_dir / f"{name}.csv")

    # --- Report --------------------------------------------------------------
    sig = granger[(granger < 0.05).any(axis=1)].index.tolist()
    md = f"""# EDA and diagnostics (M2)

Generated by `python -m fxforecast.experiments.eda`. Panel {panel.index[0]:%Y-%m} to {panel.index[-1]:%Y-%m}; features start {feats.index[0]:%Y-%m} (12-month changes need a year of history).
**All tests use the training period only ({feats_train.index[0]:%Y-%m} to {train_end:%Y-%m}, {len(feats_train)} months)** so the test period does not influence model choices.

## Key findings
- **Random-walk reference:** "no change" forecasts over the paper's test period ({rep['test_start']:%Y-%m} to {rep['test_end']:%Y-%m}) give level MAPE = **{rw_mape:.4f}**, i.e. "accuracy" = **{100 * (1 - rw_mape):.2f}%**. The paper reports VAR 96.31%, SVR 97.17%, LSTM 97.83% (on Bloomberg data).
- **Target autocorrelation:** Ljung-Box p-value at lag 1 = {lb['lb_pvalue'].iloc[0]:.3f}, at lag 12 = {lb['lb_pvalue'].iloc[-1]:.3f} (low p = past FX changes carry some information). Caution: `EXINUS` is a **monthly average** of daily rates, and averaging a random walk by itself creates positive lag-1 autocorrelation (about 0.25) in its changes (Working, 1960). Part of this "predictability" is therefore an artefact of averaging. That makes an AR(1) baseline essential in M4, alongside the random walk.
- **Granger causality** (5%, any of lags 1/3/6): {', '.join(sig) if sig else 'none of the macro differentials'}.
- **Cointegration** among log FX, relative prices, output, money and the rate differential: Johansen rank = **{rank}** at 5% (rank > 0 suggests a VECM in M5).
- **VAR lag order** on the stationary features: {lag_sel}.
- **Strongest correlations with the target (train):** {', '.join(f'{k} ({v:+.2f})' for k, v in corr_target.head(3).items())}.

## Data events to keep in mind
- **India interest rate is effectively a policy rate.** `IRSTCI01INM156N` equals the RBI central-bank rate (`IRSTCB01INM156N`) in 346 of 349 months. It sits at exactly 6.0% from 2003 to early 2012, including 2008 when market call-money rates spiked. `rate_diff` therefore measures a *policy-rate* differential. See decision D11.
- **COVID base effects:** India IP collapsed in April 2020, so `ip_growth_diff` swings by about ±0.6 in 2020-21. These are extreme values for the extension test period. Any scaling or clipping must be fit on training data only.
- **US reserves jump in Aug 2021** (IMF SDR allocation), visible in `reserves_growth_diff`.

## Figures
![raw series](figures/raw_series.png)
![features](figures/features.png)
![correlation](figures/correlation_train.png)
![acf](figures/acf_dlog_fx.png)

## Stationarity of features (ADF H0: unit root; KPSS H0: stationary)
`diff_order_used` = how many times each feature is differenced before entering the VAR (from ADF on train).

{to_markdown(stat_feats)}

## Stationarity of raw (log) levels
{to_markdown(stat_levels)}

## Granger causality: p-values for "feature does not Granger-cause {TARGET}"
{to_markdown(granger)}

## Johansen trace test (log levels; k_ar_diff = {max(lev_lag - 1, 1)})
{to_markdown(johansen)}

## Ljung-Box on {TARGET}
{to_markdown(lb)}
"""
    report = out_dir / "README.md"
    report.write_text(md, encoding="utf-8")
    log.info("EDA written to %s in %.1fs", out_dir, time.perf_counter() - started)
    return report


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", default=str(DEFAULT_CONFIG))
    parser.add_argument("--out", default=str(PROJECT_ROOT / "results" / "eda"))
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    print(run(load_config(args.config), Path(args.out)))


if __name__ == "__main__":
    main()
